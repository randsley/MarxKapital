println("\n[6b] Rationing variants (Portugal 2022, real A)...")
"""κ of every sector at state X, by the rationing step of `system_Ndept_io!`."""
function κ_of(X, p)
    N = length(p.e)
    C, V = X[1:N], X[N+1:2N]
    S = p.e .* V
    x = _gross_output(p.δ .* C .+ V .+ S, p)
    O = _investable_supply(x, p)
    return haskey(p, :capital_goods) ? _solve_rationing(p.capital_goods, ones(N), p.σ_c .* S, O) :
           _solve_rationing(p.A, ones(N), p.σ_c .* S .* x ./ C, O)
end
with_σ_v(depts, σv) = [Department(d.name, d.c, d.v, d.e, d.k, d.σ_c, σv, 1 - d.σ_c - σv, d.δ) for d in depts]
variants = [("\\(O=x\\)", false, false, false, nothing),
            ("\\(O=(1-\\varphi)x\\)", false, false, false, nothing),
            ("\\quad + imported inputs", true, false, false, nothing),
            ("\\quad + netted, demand \\(A\\Delta x\\)", true, true, false, nothing),
            ("\\quad + netted, capital goods", true, true, true, nothing),
            ("\\(O=(1-\\varphi)x\\) + imports, \\(\\sigma_v=0.01\\)", true, false, false, 0.01),
            ("\\quad + netted, capital goods, \\(\\sigma_v=0.01\\)", true, true, true, 0.01)]
rv = Dict{Tuple{Int,Int},NTuple{4,Float64}}()
rv_N = Int[]
σv_cal = NaN
for agg in (:medium, :detailed)
    pa = redirect_stdout(devnull) do
        calibrate_portugal_model(year = 2022, data_source = :eurostat, aggregation = agg)
    end
    fd = pa.final_demand
    φ = exogenous_demand_share(fd)
    b = capital_goods_composition(fd; A = pa.A)
    d0 = departments_from_params(pa)
    global σv_cal = d0[1].σ_v
    push!(rv_N, pa.N)
    for (k, (_, imports, net, goods, σv)) in enumerate(variants)
        kw = (coupled = true, rationing = true, A = pa.A,
              final_demand_share = k == 1 ? nothing : φ, net_intermediate = net,
              capital_goods = goods ? b : nothing, benchmark_output = goods ? fd.output : nothing,
              import_coefficients = imports ? pa.import_coefficients : nothing)
        sol, _, p = redirect_stderr(devnull) do
            simulate_Ndept_custom(isnothing(σv) ? d0 : with_σ_v(d0, σv); T = 30.0, kw...)
        end
        κs = [κ_of(X, p) for X in sol.u]
        early = [κ_of(sol(t), p) for t in 0.0:0.5:10.0]
        rv[(pa.N, k)] = (mean([mean(κ .< 0.999) for κ in κs]), mean(mean.(early)),
                         sum(sol.u[end][1:pa.N]) / sum(sol.u[1][1:pa.N]), mean(κ_of(sol.u[1], p)))
        @printf("  ✓ N=%d %-48s rationed %.2f  mean κ (0–10) %.3f  ΣC ×%.2f  κ(0) %.2f\n",
                pa.N, variants[k][1], rv[(pa.N, k)]...)
    end
end
growth_cell(g) = g >= 10 ? @sprintf("\\(\\times\\)%.1f", g) : @sprintf("\\(\\times\\)%.2f", g)
