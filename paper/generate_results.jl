            @printf(io, "\\newcommand{\\PIM%sGap%s}{%.1f}\n", name, tag, gap)
            @printf(io, "\\newcommand{\\PIM%sMad%s}{%.1f}\n", name, tag, mad)
            println(io, "\\newcommand{\\PIM$(name)Within$(tag)}{$within}")
            @printf("  ✓ %d %-6s aggregate gap %+.1f%%, mean |section gap| %.1f%%, %d/%d within 10%%\n",
                    yr, name, gap, mad, within, length(K))
        end
        yr == 2022 && println(io, "\\newcommand{\\PIMSections}{$(length(rep))}")
    end
end

